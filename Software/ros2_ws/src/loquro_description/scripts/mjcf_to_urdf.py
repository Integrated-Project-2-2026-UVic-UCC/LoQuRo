#!/usr/bin/env python3
"""Generates urdf/loquro_body.xacro from the MuJoCo model (Software/control/loquro_lab).

Visualization only: every part is fixed at the standing pose of the simulation (the legs are closed kinematic
chains that URDF cannot represent, and there are no encoders to animate them). One link per leg plus a foot frame.

Usage (needs `pip install mujoco numpy`):
    python3 mjcf_to_urdf.py <path to loquro.xml>
Run it again when the MuJoCo model changes.
"""
import ast
import re
import shutil
import sys
from pathlib import Path

import mujoco
import numpy as np

PKG = Path(__file__).resolve().parents[1]
LEGS = {'fl': 'lf', 'fr': 'rf', 'rl': 'lh', 'rr': 'rh'}  # simulation name -> firmware name


def stance_qpos(xml: Path) -> dict:
    """QUAD_JOINT_POS from quad_bot_constants.py, read as text (it imports mjlab)."""
    src = (xml.parents[1] / 'quad_bot_constants.py').read_text()
    return ast.literal_eval(re.search(r'QUAD_JOINT_POS = (\{.*?\})', src, re.S).group(1))


def mat(q):
    r = np.zeros(9)
    mujoco.mju_quat2Mat(r, q)
    return r.reshape(3, 3)


def rpy(r):
    """Rotation matrix -> URDF roll pitch yaw (R = Rz(yaw) Ry(pitch) Rx(roll))."""
    pitch = np.arcsin(-np.clip(r[2, 0], -1, 1))
    if abs(np.cos(pitch)) > 1e-6:
        return np.arctan2(r[2, 1], r[2, 2]), pitch, np.arctan2(r[1, 0], r[0, 0])
    return np.arctan2(-r[1, 2], r[1, 1]), pitch, 0.0


def origin(p, r):
    return '<origin xyz="%.5f %.5f %.5f" rpy="%.5f %.5f %.5f"/>' % (*p, *rpy(r))


def main():
    xml = Path(sys.argv[1]).resolve()
    m = mujoco.MjModel.from_xml_path(str(xml))
    d = mujoco.MjData(m)

    # standing pose, trunk at the origin
    d.qpos[:7] = [0, 0, 0, 1, 0, 0, 0]
    for name, value in stance_qpos(xml).items():
        d.qpos[m.jnt_qposadr[mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, name)]] = value
    mujoco.mj_forward(m, d)

    def body(name):
        i = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_BODY, name)
        return d.xpos[i].copy(), d.xmat[i].reshape(3, 3).copy()

    def owner(geom):  # leg prefix of the body that holds the geom, '' for the trunk
        b = mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_BODY, m.geom_bodyid[geom])
        return b[:2] if b[:2] in LEGS else ''

    frames = {'': body('trunk')}
    frames.update({leg: body(leg + '_mount') for leg in LEGS})
    visuals = {k: [] for k in frames}
    used_meshes = set()

    for g in range(m.ngeom):
        if m.geom_type[g] != mujoco.mjtGeom.mjGEOM_MESH or m.geom_group[g] != 1:
            continue
        mesh = m.geom_dataid[g]
        # MuJoCo recenters meshes: undo it to place the original STL file
        r_mesh = mat(m.mesh_quat[mesh])
        r_file = d.geom_xmat[g].reshape(3, 3) @ r_mesh.T
        p_file = d.geom_xpos[g] - r_file @ m.mesh_pos[mesh]

        leg = owner(g)
        p0, r0 = frames[leg]
        p_rel, r_rel = r0.T @ (p_file - p0), r0.T @ r_file

        file = MESH_FILES[mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_MESH, mesh)]
        used_meshes.add(file)
        rgba = ' '.join('%.2f' % c for c in m.geom_rgba[g])
        visuals[leg].append(
            f'    <visual>\n      {origin(p_rel, r_rel)}\n'
            f'      <geometry><mesh filename="package://loquro_description/meshes/{file}" scale="0.001 0.001 0.001"/></geometry>\n'
            f'      <material name=""><color rgba="{rgba}"/></material>\n    </visual>')

    out = ['<?xml version="1.0"?>',
           '<!-- GENERATED by scripts/mjcf_to_urdf.py from the MuJoCo model. Do not edit, run the script again. -->',
           '<robot xmlns:xacro="http://www.ros.org/wiki/xacro">',
           '  <link name="base_link">', *visuals[''], '  </link>']
    for sim, ros in LEGS.items():
        p, r = frames[sim]
        out += [f'  <link name="{ros}_leg">', *visuals[sim], '  </link>',
                f'  <joint name="{ros}_leg_mount" type="fixed">', '    <parent link="base_link"/>',
                f'    <child link="{ros}_leg"/>', f'    {origin(p, r)}', '  </joint>']
        # foot frame: center of the foot contact sphere
        foot = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_GEOM, sim + '_foot_collision')
        out += [f'  <link name="{ros}_foot"/>', f'  <joint name="{ros}_foot_joint" type="fixed">',
                '    <parent link="base_link"/>', f'    <child link="{ros}_foot"/>',
                f'    {origin(d.geom_xpos[foot], np.eye(3))}', '  </joint>']
    out.append('</robot>\n')
    (PKG / 'urdf' / 'loquro_body.xacro').write_text('\n'.join(out))

    for f in sorted(used_meshes):
        shutil.copy(xml.parent / 'assets' / f, PKG / 'meshes' / f)
    print(f'urdf/loquro_body.xacro written, {len(used_meshes)} meshes copied')


# mesh name -> file, read from the MJCF (MjModel does not keep file names)
MESH_FILES = {}
if __name__ == '__main__':
    MESH_FILES.update(dict(re.findall(r'<mesh name="([^"]+)" file="([^"]+)"', Path(sys.argv[1]).read_text())))
    main()
